md("## Time each model")
code(r"""
RUNS = ["E1_lora_0.5B_saq+mcq", "E3_lora_1.5B_saq+mcq"]
MAX_NEW_TOKENS = 200   # same cap the app uses
RESULTS = []
proc = psutil.Process()

for name in RUNS:
    adapter = f"{OUT_ROOT}/{name}/adapter"
    if not os.path.exists(adapter):
        print("missing adapter:", adapter); continue
    gc.collect()
    t0 = time.perf_counter()
    a = Assistant.load(EXPERIMENTS[name]["model"], adapter, gate_path=None, threads=os.cpu_count(),
                       max_new_tokens=MAX_NEW_TOKENS)
    load_s = time.perf_counter() - t0
    rss_gb = proc.memory_info().rss / 1e9
    print(f"\n=== {name}: loaded in {load_s:.0f}s, process RAM {rss_gb:.1f} GB", flush=True)
    a.respond("warm up")  # first call pays one-off costs
    rows = []
    for q in QUESTIONS:
        r = a.respond(q)
        n_tok = len(a.tok(r["answer"], add_special_tokens=False)["input_ids"])
        rows.append({"question": q, "seconds": r["seconds"], "new_tokens": n_tok, "answer": r["answer"]})
        print(f"  {r['seconds']:5.1f}s  {n_tok:3d} tok  Q: {q[:70]}\n         A: {r['answer'][:200]}", flush=True)
    secs = [x["seconds"] for x in rows]
    RESULTS.append({
        "experiment": name, "load_seconds": round(load_s, 1), "process_ram_gb": round(rss_gb, 2),
        "mean_seconds": round(sum(secs) / len(secs), 1), "max_seconds": round(max(secs), 1),
        "tokens_per_second": round(sum(x["new_tokens"] for x in rows) / sum(secs), 2),
        "mean_new_tokens": round(sum(x["new_tokens"] for x in rows) / len(rows), 1),
        "answers": rows,
    })
    del a; gc.collect()
""")

