def multi_letter_rate(name):
    # Share of single-answer test MCQs where the generated answer listed more than one letter.
    p = f"{OUT_ROOT}/{name}/predictions_test.jsonl"
    if not os.path.exists(p):
        return None
    single = [r for r in load_jsonl(p) if r["question_type"] == "mcq" and not r["multi_answer"]]
    return round(sum(bool(r["parsed"]) and len(r["parsed"]) > 1 for r in single) / len(single), 4)

rows = []
for name in EXPERIMENTS:
    mp, lp = f"{OUT_ROOT}/{name}/metrics.json", f"{OUT_ROOT}/{name}/mcq_likelihood.json"
    if not (os.path.exists(mp) and os.path.exists(lp)):
        continue
    m, l = json.load(open(mp)), json.load(open(lp))
    t, h = m["test"], m["history"] or {}
    rows.append({
        "experiment": name,
        "test_mcq_likelihood_single": l["test"]["single"]["acc"],
        "test_mcq_likelihood_single_ci95": l["test"]["single"]["acc_ci95"],
        "test_mcq_likelihood_expert": l["test"]["single_by"]["tier=expert"]["acc"],
        "test_mcq_likelihood_african": l["test"]["single_by"]["african_expertise"]["acc"],
        "test_mcq_gen_exact": t["mcq"]["acc"], "test_mcq_gen_single": t["mcq_by"]["single"]["acc"],
        "test_gen_multi_letter_rate_on_single": multi_letter_rate(name),
        "test_saq_rougeL": t["saq"]["rougeL"], "test_saq_rougeL_ci95": t["saq"]["rougeL_ci95"],
        "test_saq_bertscore": t["saq"]["bertscore_f1"], "test_saq_bertscore_ci95": t["saq"]["bertscore_ci95"],
        "test_saq_pred_words": t["saq"]["pred_words"],
        "val_mcq_likelihood_single": l["val"]["single"]["acc"], "val_saq_rougeL": m["val"]["saq"]["rougeL"],
        "best_epoch": h.get("best_epoch"), "train_min": h.get("train_minutes"),
    })
TABLE2 = pd.DataFrame(rows)
TABLE2.to_csv(f"{OUT_ROOT}/experiments_table_v2.csv", index=False)
pd.set_option("display.max_columns", None)
